function setText(selector, value) {
  document.querySelectorAll(selector).forEach((element) => {
    element.textContent = value;
  });
}

function setHtml(selector, html) {
  const element = document.querySelector(selector);
  if (element) element.innerHTML = html;
}

function renderHeroTitle() {
  const html = siteData.hero.lines
    .map((line, index) => {
      const match = line.match(/^(.*?)([。！？!?]*)$/);
      const text = escapeHtml(match ? match[1] : line);
      const punct = match && match[2] ? `<span class="punct">${escapeHtml(match[2])}</span>` : "";
      return `<span class="line"><span style="--d:${(0.15 + index * 0.14).toFixed(2)}s">${text}${punct}</span></span>`;
    })
    .join("");
  setHtml("[data-hero-title]", html);
}

